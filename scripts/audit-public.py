#!/usr/bin/env python3
"""Check first-party source and artifacts without printing sensitive values."""
from pathlib import Path
import re
import sys
import tarfile


EXCLUDED = {'.git', '.cache', 'target', '__pycache__', 'vendor'}
# The browser filesystem and anonymous Rust toolchain remaps are intentional.
HOME_ALLOWLIST = {'/home/web', '/home/.cargo', '/home/.rustup'}
HOME_PATH = re.compile(r'/(?:Users|Volumes|home)/[\w.-]+')
PATTERNS = {
    'native Windows path': re.compile(r'(?<!\w)[A-Za-z]:[\\/]+[\w][\w. -]{2,}[\\/]+[\w.-]'),
    'native root home path': re.compile(r'/root(?:/|(?=[\s\x00\'"<>]|$))'),
    'generated attribution': re.compile(r'\b(?:Co-Authored-By|generated by (?:AI|an agent)|Claude|Codex)\b', re.I),
    'credential-shaped value': re.compile(
        r'\b(?:A(?:KIA|SIA)[A-Z0-9]{16}|gh[pousr]_[A-Za-z0-9]{30,}|'
        r'github_pat_[A-Za-z0-9_]{30,}|(?:sk|rk)_(?:live|test)_[A-Za-z0-9]{16,}|'
        r'whsec_[A-Za-z0-9]{16,}|sk-(?:proj-|svcacct-)?[A-Za-z0-9_-]{32,}|'
        r'xox[baprs]-[A-Za-z0-9-]{16,}|xapp-[A-Za-z0-9-]{16,}|AIza[A-Za-z0-9_-]{35})\b'),
    'private key': re.compile(r'-----BEGIN (?:[A-Z0-9]+ )*PRIVATE KEY(?: BLOCK)?-----'),
}


def inspect_data(data, label):
    """Inspect embedded UTF-8 strings and BOM-marked UTF-16 text."""
    encoding = 'utf-16' if data.startswith((b'\xff\xfe', b'\xfe\xff')) else 'utf-8'
    try:
        text = data.decode(encoding)
    except UnicodeError:
        # Preserve separators between printable strings in compiled artifacts.
        text = re.sub(r'[^\x20-\x7e\n]', '\x00', data.decode('latin1'))
        if label.replace('\\', '/') == 'assets/wasm/terminal.wasm':
            # Rust's string pool joins virtual /home and /home/web with a quote.
            text = text.replace("/home/home/web'\x00", "/home/web'\x00")
    failures = []
    for number, line in enumerate(text.splitlines(), 1):
        categories = [category for category, pattern in PATTERNS.items() if pattern.search(line)]
        if any(match.group() not in HOME_ALLOWLIST for match in HOME_PATH.finditer(line)):
            categories.append('native user home path')
        failures.extend(f'{label}:{number}: {category}' for category in categories)
    return failures


def audit(root):
    failures = []
    for path in sorted(root.rglob('*')):
        relative = path.relative_to(root)
        if not path.is_file() or any(part in EXCLUDED for part in relative.parts):
            continue
        if path.resolve() == Path(__file__).resolve():
            continue
        try:
            if path.name.endswith(('.tar.gz', '.tgz')):
                with tarfile.open(path) as archive:
                    for member in archive:
                        label = f'{relative}:{member.name}'
                        if member.uname or member.gname or member.uid or member.gid:
                            failures.append(f'{label}: archive contains owner metadata')
                        if member.isfile():
                            failures.extend(inspect_data(archive.extractfile(member).read(), label))
            else:
                failures.extend(inspect_data(path.read_bytes(), str(relative)))
        except (OSError, tarfile.TarError):
            failures.append(f'{relative}: file could not be audited')
    return failures


def main():
    failures = audit(Path(__file__).resolve().parents[1])
    if failures:
        print('\n'.join(failures))
        return 1
    print('Public-source and compiled-string audit passed.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
