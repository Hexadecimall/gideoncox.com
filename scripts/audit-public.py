#!/usr/bin/env python3
"""Check first-party text and compiled artifacts for private build residue."""
from pathlib import Path
import re
import subprocess
import sys

root = Path(__file__).resolve().parents[1]
patterns = [
    re.compile(r'/(?:Users|Volumes)/[^\s]+'),
    re.compile(r'\b(?:Co-Authored-By|generated by (?:AI|an agent)|Claude|Codex)\b', re.I),
    re.compile(r'\b(?:AKIA[A-Z0-9]{16}|ghp_[A-Za-z0-9]{30,}|github_pat_[A-Za-z0-9_]+)\b'),
]
failures = []
for path in root.rglob('*'):
    relative = path.relative_to(root)
    if not path.is_file() or any(part in {'.git', '.cache', 'target', '__pycache__', 'vendor'} for part in relative.parts):
        continue
    if path == Path(__file__).resolve():
        continue
    if path.suffix == '.wasm':
        text = subprocess.check_output(['strings', str(path)], text=True)
    else:
        try:
            text = path.read_text()
        except (UnicodeError, OSError):
            continue
    for number, line in enumerate(text.splitlines(), 1):
        if any(pattern.search(line) for pattern in patterns):
            failures.append(f'{relative}:{number}: private residue detected')
if failures:
    print('\n'.join(failures))
    sys.exit(1)
print('Public-source and compiled-string audit passed.')
